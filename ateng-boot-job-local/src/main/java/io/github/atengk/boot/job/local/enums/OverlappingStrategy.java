package io.github.atengk.boot.job.local.enums;

/**
 * 任务并发重叠执行策略枚举
 * <p>
 * 当上一次任务调度尚未执行完毕，且下一个触发周期已经到来时的互斥防卫策略。
 * </p>
 *
 * @author Ateng
 * @since 2026-10-25
 */
public enum OverlappingStrategy {

    /**
     * 丢弃跳过策略（默认生产推荐 / 防雪崩）
     * <p>
     * 若上一次任务仍在执行中，直接放弃并跳过当前触发周期，避免产生并发重叠与线程池耗尽。
     * </p>
     */
    DISCARD,

    /**
     * 串行排队策略
     * <p>
     * 若上一次任务仍在执行中，当前周期进入 FIFO 队列等待上一次执行结束，保证每次调度均被严格串行执行。
     * </p>
     */
    QUEUE,

    /**
     * 并发并行策略
     * <p>
     * 允许同名任务在独立线程中并发并行执行，任务之间完全互不干扰。
     * </p>
     */
    CONCURRENT,

    /**
     * 强行抢占中断策略
     * <p>
     * 尝试向正在执行中的上一次任务线程发送 {@link Thread#interrupt()} 中断信号，并强行开启当前新周期的执行。
     * </p>
     */
    INTERRUPT
}
